// MARK: - Notes

struct Note: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String
    var done = false
    var pinned = false
    var created = Date()
}

final class NotesStore: ObservableObject {
    @Published private(set) var notes: [Note] = []
    var persist = true
    private let url: URL

    init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Aries", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        url = dir.appendingPathComponent("notes.json")
        if let d = try? Data(contentsOf: url), let n = try? JSONDecoder().decode([Note].self, from: d) { notes = n }
    }

    var sorted: [Note] {
        notes.sorted {
            if $0.pinned != $1.pinned { return $0.pinned }
            if $0.done != $1.done { return !$0.done }
            return $0.created > $1.created
        }
    }

    var openCount: Int { notes.filter { !$0.done }.count }

    func add(_ text: String) {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty else { return }
        notes.append(Note(text: t))
        save()
    }

    func toggle(_ n: Note) { mutate(n) { $0.done.toggle() } }
    func togglePin(_ n: Note) { mutate(n) { $0.pinned.toggle() } }
    func delete(_ n: Note) { notes.removeAll { $0.id == n.id }; save() }
    func clearDone() { notes.removeAll { $0.done }; save() }
    func copy(_ n: Note) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(n.text, forType: .string)
    }

    private func mutate(_ n: Note, _ f: (inout Note) -> Void) {
        guard let i = notes.firstIndex(where: { $0.id == n.id }) else { return }
        f(&notes[i]); save()
    }

    private func save() {
        guard persist else { return }
        if let d = try? JSONEncoder().encode(notes) { try? d.write(to: url, options: .atomic) }
    }
}

// MARK: - Clipboard history (opt-in, memory only, skips password managers)

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
}

final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private static let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                     "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Prefs.bool(Prefs.showClipboard) else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes), let s = pb.string(forType: .string) else { return }
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty, t.count < 5000 else { return }
        items.removeAll { $0.text == t }
        items.insert(ClipItem(text: t, date: Date()), at: 0)
        if items.count > 30 { items.removeLast(items.count - 30) }
    }

    func copy(_ item: ClipItem) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(item.text, forType: .string)
        lastChange = NSPasteboard.general.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(ClipItem(text: item.text, date: Date()), at: 0)
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll() }
}

// MARK: - Weather (Open-Meteo, no API key, city chosen in Settings)

final class WeatherModel: ObservableObject {
    @Published private(set) var temperature: Double?
    @Published private(set) var high: Double?
    @Published private(set) var low: Double?
    @Published private(set) var code: Int = 0
    @Published private(set) var isDay = true
    @Published private(set) var city = Prefs.string(Prefs.weatherCity)
    @Published private(set) var status = ""
    private var timer: Timer?

    var symbol: String { Self.symbol(code: code, day: isDay) }
    var summary: String { Self.summary(code: code) }
    var unit: String { Prefs.bool(Prefs.fahrenheit) ? "°F" : "°C" }

    func start() {
        refresh()
        timer = Timer.scheduledTimer(withTimeInterval: 20 * 60, repeats: true) { [weak self] _ in self?.refresh() }
    }

    /// Looks up a city name and saves its coordinates.
    func setCity(_ name: String) {
        let q = name.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return }
        status = "Searching…"
        var c = URLComponents(string: "https://geocoding-api.open-meteo.com/v1/search")!
        c.queryItems = [.init(name: "name", value: q), .init(name: "count", value: "1")]
        Task {
            guard let (data, _) = try? await URLSession.shared.data(from: c.url!),
                  let j = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let r = (j["results"] as? [[String: Any]])?.first,
                  let lat = r["latitude"] as? Double, let lon = r["longitude"] as? Double else {
                await MainActor.run { self.status = "Couldn't find that city" }
                return
            }
            let label = [r["name"] as? String, r["admin1"] as? String].compactMap { $0 }.joined(separator: ", ")
            await MainActor.run {
                UserDefaults.standard.set(label, forKey: Prefs.weatherCity)
                UserDefaults.standard.set(lat, forKey: Prefs.weatherLat)
                UserDefaults.standard.set(lon, forKey: Prefs.weatherLon)
                self.city = label
                self.status = ""
                self.refresh()
            }
        }
    }

    func refresh() {
        let d = UserDefaults.standard
        guard d.object(forKey: Prefs.weatherLat) != nil else { return }
        let lat = d.double(forKey: Prefs.weatherLat), lon = d.double(forKey: Prefs.weatherLon)
        var c = URLComponents(string: "https://api.open-meteo.com/v1/forecast")!
        c.queryItems = [
            .init(name: "latitude", value: String(lat)), .init(name: "longitude", value: String(lon)),
            .init(name: "current", value: "temperature_2m,weather_code,is_day"),
            .init(name: "daily", value: "temperature_2m_max,temperature_2m_min"),
            .init(name: "timezone", value: "auto"), .init(name: "forecast_days", value: "1"),
            .init(name: "temperature_unit", value: Prefs.bool(Prefs.fahrenheit) ? "fahrenheit" : "celsius"),
        ]
        Task {
            guard let (data, _) = try? await URLSession.shared.data(from: c.url!),
                  let j = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let cur = j["current"] as? [String: Any] else { return }
            let daily = j["daily"] as? [String: Any]
            await MainActor.run {
                self.temperature = cur["temperature_2m"] as? Double
                self.code = cur["weather_code"] as? Int ?? 0
                self.isDay = (cur["is_day"] as? Int ?? 1) == 1
                self.high = (daily?["temperature_2m_max"] as? [Double])?.first
                self.low = (daily?["temperature_2m_min"] as? [Double])?.first
                self.city = Prefs.string(Prefs.weatherCity)
            }
        }
    }

    static func symbol(code: Int, day: Bool) -> String {
        switch code {
        case 0: return day ? "sun.max.fill" : "moon.stars.fill"
        case 1, 2: return day ? "cloud.sun.fill" : "cloud.moon.fill"
        case 3: return "cloud.fill"
        case 45, 48: return "cloud.fog.fill"
        case 51...57: return "cloud.drizzle.fill"
        case 61...67, 80...82: return "cloud.rain.fill"
        case 71...77, 85, 86: return "cloud.snow.fill"
        case 95...99: return "cloud.bolt.rain.fill"
        default: return "cloud.fill"
        }
    }

    static func summary(code: Int) -> String {
        switch code {
        case 0: return "Clear"
        case 1: return "Mostly clear"
        case 2: return "Partly cloudy"
        case 3: return "Cloudy"
        case 45, 48: return "Fog"
        case 51...57: return "Drizzle"
        case 61...67: return "Rain"
        case 80...82: return "Showers"
        case 71...77, 85, 86: return "Snow"
        case 95...99: return "Thunderstorms"
        default: return ""
        }
    }
}

// MARK: - Mirror (camera preview)

final class MirrorCamera: ObservableObject {
    @Published private(set) var authorized = AVCaptureDevice.authorizationStatus(for: .video) == .authorized
    @Published private(set) var running = false
    let session = AVCaptureSession()
    private var configured = false
    private let queue = DispatchQueue(label: "aries.mirror")

    func start() {
        switch AVCaptureDevice.authorizationStatus(for: .video) {
        case .authorized: authorized = true; begin()
        case .notDetermined:
            AVCaptureDevice.requestAccess(for: .video) { ok in
                DispatchQueue.main.async { self.authorized = ok; if ok { self.begin() } }
            }
        default: authorized = false
        }
    }

    private func begin() {
        AppDelegate.shared?.system.ownCameraInUse = true
        queue.async {
            if !self.configured {
                self.session.sessionPreset = .high
                if let dev = AVCaptureDevice.default(for: .video), let input = try? AVCaptureDeviceInput(device: dev),
                   self.session.canAddInput(input) {
                    self.session.addInput(input)
                }
                self.configured = true
            }
            if !self.session.isRunning { self.session.startRunning() }
            DispatchQueue.main.async { self.running = true }
        }
    }

    func stop() {
        queue.async {
            if self.session.isRunning { self.session.stopRunning() }
            DispatchQueue.main.async {
                self.running = false
                DispatchQueue.main.asyncAfter(deadline: .now() + 3) { AppDelegate.shared?.system.ownCameraInUse = false }
            }
        }
    }
}

struct CameraPreview: NSViewRepresentable {
    let session: AVCaptureSession
    func makeNSView(context: Context) -> NSView {
        let v = NSView()
        v.wantsLayer = true
        let layer = AVCaptureVideoPreviewLayer(session: session)
        layer.videoGravity = .resizeAspectFill
        layer.connection?.automaticallyAdjustsVideoMirroring = false
        layer.connection?.isVideoMirrored = true
        layer.autoresizingMask = [.layerWidthSizable, .layerHeightSizable]
        v.layer = layer
        return v
    }
    func updateNSView(_ nsView: NSView, context: Context) {
        if let l = nsView.layer as? AVCaptureVideoPreviewLayer, l.connection?.isVideoMirrored == false {
            l.connection?.automaticallyAdjustsVideoMirroring = false
            l.connection?.isVideoMirrored = true
        }
    }
}

// MARK: - Global keyboard shortcuts (no Accessibility permission needed)

final class Hotkeys {
    static let shared = Hotkeys()
    private var actions: [UInt32: () -> Void] = [:]
    private var refs: [EventHotKeyRef?] = []
    private var installed = false

    struct Shortcut { let id: UInt32; let key: Int; let title: String; let glyph: String }
    static let all: [Shortcut] = [
        .init(id: 1, key: kVK_ANSI_I, title: "Open the island", glyph: "⌥⌘I"),
        .init(id: 2, key: kVK_ANSI_P, title: "Play / pause", glyph: "⌥⌘P"),
        .init(id: 3, key: kVK_ANSI_L, title: "Full-screen lyrics", glyph: "⌥⌘L"),
        .init(id: 4, key: kVK_ANSI_N, title: "New note", glyph: "⌥⌘N"),
        .init(id: 5, key: kVK_ANSI_M, title: "Mute / unmute microphone", glyph: "⌥⌘M"),
        .init(id: 6, key: kVK_ANSI_K, title: "Like current song", glyph: "⌥⌘K"),
    ]

    func register(_ handlers: [UInt32: () -> Void]) {
        unregister()
        guard Prefs.bool(Prefs.hotkeys) else { return }
        actions = handlers
        if !installed {
            installed = true
            var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            InstallEventHandler(GetApplicationEventTarget(), { _, event, _ in
                var hk = EventHotKeyID()
                GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID),
                                  nil, MemoryLayout<EventHotKeyID>.size, nil, &hk)
                DispatchQueue.main.async { Hotkeys.shared.actions[hk.id]?() }
                return noErr
            }, 1, &spec, nil, nil)
        }
        for s in Self.all {
            var ref: EventHotKeyRef?
            let id = EventHotKeyID(signature: OSType(0x41524953), id: s.id) // 'ARIS'
            RegisterEventHotKey(UInt32(s.key), UInt32(cmdKey | optionKey), id, GetApplicationEventTarget(), 0, &ref)
            refs.append(ref)
        }
    }

    func unregister() {
        for r in refs { if let r { UnregisterEventHotKey(r) } }
        refs.removeAll()
    }
}
